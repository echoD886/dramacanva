export function checkoutReturnState(paymentState: string, payment: string, elapsed: number) {
    if (paymentState === "succeeded") return "success";
    if (payment === "cancel" || payment === "cancelled") return "cancelled";
    return elapsed >= checkoutPollLimit ? "delayed" : "confirming";
}
export function checkoutPollDelay(index: number) {
    return checkoutPollDelays[Math.min(index, checkoutPollDelays.length - 1)];
}
export function checkoutOrigin(value: string | null) {
    return value?.startsWith("/") && !value.startsWith("//") && !value.startsWith("/pricing") ? value : "/canvas";
}
