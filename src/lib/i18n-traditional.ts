// The conversion is pure, and the same article bodies and catalog strings are converted many
// times (SEO resolution walks every locale per page). Cache results, bounded for long sessions.
const TRADITIONAL_CACHE_LIMIT = 20_000;
const traditionalCache = { "zh-HK": new Map<string, string>(), "zh-TW": new Map<string, string>() };

export function toTraditionalChinese(text: string, locale: "zh-HK" | "zh-TW" = "zh-TW"): string {
    if (!text) return "";
    const cache = traditionalCache[locale];
    const cached = cache.get(text);
    if (cached !== undefined) return cached;
    const result = convertToTraditional(text, locale);
    if (cache.size >= TRADITIONAL_CACHE_LIMIT) cache.clear();
    cache.set(text, result);
    return result;
}

function convertToTraditional(text: string, locale: "zh-HK" | "zh-TW"): string {
    let converted = text
        .replace(/特征/g, "特徵")
        .replace(/采用/g, "採用")
        .replace(/采样/g, "採樣")
        .replace(/采集/g, "採集")
        .replace(/采纳/g, "採納")
        .replace(/采购/g, "採購")
        .replace(/采光/g, "採光")
        .replace(/占用/g, "佔用")
        .replace(/占比/g, "佔比")
        .replace(/占据/g, "佔據")
        .replace(/合并/g, "合併")
        .replace(/并排/g, "並排")
        .replace(/复制/g, "複製")
        .replace(/录制/g, "錄製")
        .replace(/绘制/g, "繪製")
        .replace(/定制/g, "定製")
        .replace(/压制/g, "壓製")
        .replace(/编制/g, "編製")
        .replace(/仿制/g, "仿製")
        .replace(/特制/g, "特製")
        .replace(/预制/g, "預製")
        .replace(/恢复/g, "恢復")
        .replace(/修复/g, "修復")
        .replace(/复原/g, "復原")
        .replace(/复古/g, "復古")
        .replace(/往复/g, "往復")
        .replace(/复活/g, "復活")
        .replace(/批复/g, "批覆")
        .replace(/答复/g, "答覆")
        .replace(/覆盖/g, "覆蓋")
        .replace(/颠覆/g, "顛覆")
        .replace(/倾覆/g, "傾覆")
        .replace(/躯干/g, "軀幹")
        .replace(/树干/g, "樹幹")
        .replace(/主干/g, "主幹")
        .replace(/骨干/g, "骨幹")
        .replace(/干净/g, "乾淨")
        .replace(/干燥/g, "乾燥")
        .replace(/干脆/g, "乾脆")
        .replace(/饼干/g, "餅乾");
    // 1. 优先替换行业特定术语
    const termRules = locale === "zh-HK" ? HK_TERM_REPLACEMENTS : TW_TERM_REPLACEMENTS;
    for (const [pattern, replacement] of termRules) {
        converted = converted.replace(pattern, replacement);
    }
    // 2. 逐字替换常用繁体字
    let result = "";
    for (const char of converted) {
        result += S2T_CHAR_MAP[char] ?? char;
    }
    result = result
        .replace(/庫布[裡裏]克/g, "庫布里克")
        .replace(/公[裡裏]/g, "公里")
        .replace(/[裡裏]程/g, "里程")
        .replace(/鄰[裡裏]/g, "鄰里")
        .replace(/英[裡裏]/g, "英里")
        .replace(/海[裡裏]/g, "海里")
        .replace(/卡路[裡裏]/g, "卡路里")
        .replace(/阿[裡裏]/g, "阿里")
        .replace(/馬德[裡裏]/g, "馬德里")
        .replace(/[裡裏]斯本/g, "里斯本")
        .replace(/[裡裏]昂/g, "里昂");
    if (locale === "zh-HK") {
        return result.replace(/裡/g, "裏");
    }
    return result.replace(/着/g, "著");
}

export function convertCatalogToTraditional(
    catalog: Record<string, string>,
    locale: "zh-HK" | "zh-TW"
): Record<string, string> {
    const result: Record<string, string> = {};
    for (const [key, value] of Object.entries(catalog)) {
        result[key] = toTraditionalChinese(value, locale);
    }
    return result;
}
