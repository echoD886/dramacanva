export function b2Text(key: string, values: Readonly<Record<string, string | number>> = {}, locale = resolveAppLocale()): string {
    const catalog = locale === "zh-HK" || locale === "zh-TW" ? traditional[locale] : catalogs[locale] || catalogs["en-US"];
    let text = catalog[key] || (key === "account.settings.channels.edit" ? currentLocaleText("directorNode.edit") : currentLocaleText(key as MessageKey));
    for (const [name, value] of Object.entries(values)) text = text.replaceAll("{{" + name + "}}", String(value));
    return text;
}
export function useB2I18n() {
    const locale = useAppLocale();
    const t = useCallback((key: string, values?: Readonly<Record<string, string | number>>) => b2Text(key, values, locale), [locale]);
    return { t };
}
