export function upstreamAPIMessage(message: string) {
    const cooldown = /^验证码请求过于频繁，请 (\d+) 秒后重试$/.exec(message);
    if (cooldown) return currentLocaleText("upstream.accountError.cooldown", { seconds: cooldown[1] });
    const key = curationErrors[message as keyof typeof curationErrors];
    return key ? currentLocaleText(key) : message;
}
