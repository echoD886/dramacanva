export function productionText(locale: string, index: number, values: Record<string, string | number> = {}) {
    const traditional = locale === "zh-TW" || locale === "zh-HK";
    const catalog = copy[traditional ? "zh-CN" : (locale as keyof typeof copy)] || copy["en-US"];
    const text = (catalog[index] || copy["en-US"][index] || "").replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match));
    return traditional ? productionTraditionalText(text, locale) : text;
}
export function useProductionText() {
    const locale = useAppLocale();
    return (index: number, values?: Record<string, string | number>) => productionText(locale, index, values);
}
