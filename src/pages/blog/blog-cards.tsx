import { ArrowRight } from "lucide-react";
import { Link } from "react-router";
import type { BlogArticle, BlogArticleIndex } from "@/content/blog";
import { getArticleCover } from "@/lib/blog-cover";
export { getArticleCover } from "@/lib/blog-cover";
import { blogPath, type BlogColumn, type BlogLocale } from "@/content/blog-locales";
import { BLOG_UI, BLOG_READING_UI, readingLabel, resolveBlogAuthor } from "@/content/blog-ui";
import { articleColumn, articleReadingMinutes } from "@/lib/blog-reading";
import { useI18n } from "@/i18n/use-i18n";
import { AuthorAvatar } from "./blog-author";

type CardArticle = BlogArticle | BlogArticleIndex;

// Generated by scripts/blog-cover-variants.py next to each 1600 px cover JPG.
const COVER_WIDTHS = [480, 960, 1600] as const;
export const BLOG_CARD_COVER_SIZES = "(max-width: 760px) calc(100vw - 32px), 470px";
export const BLOG_LEAD_COVER_SIZES = "(max-width: 1100px) calc(100vw - 32px), 860px";

/** Responsive WebP srcset for a generated cover, so cards stop downloading the 0.3-0.95 MB JPG. */
export function coverWebpSrcSet(src: string) {
    const match = /^(\/blog-media\/covers\/[a-z0-9-]+)\.jpg$/.exec(src);
    return match ? COVER_WIDTHS.map((width) => `${match[1]}-${width}.webp ${width}w`).join(", ") : undefined;
}

export function BrandedCover({ column, label }: { column: BlogColumn; label: string }) {
    return (
        <div className="isa-blog-card-cover-branded" data-column={column} aria-hidden="true">
            <span className="isa-blog-cover-brand">DramaCanvas / Journal</span>
            <strong>{label}</strong>
        </div>
    );
}

export function BlogCover({ article, locale, eager = false }: { article: CardArticle; locale: BlogLocale; eager?: boolean }) {
    const cover = getArticleCover(article, locale);
    const responsive = cover ? coverWebpSrcSet(cover.src) : undefined;
    return cover ? (
        <picture data-scroll-parallax={eager || undefined}>
            {responsive ? <source srcSet={responsive} sizes={eager ? BLOG_LEAD_COVER_SIZES : BLOG_CARD_COVER_SIZES} type="image/webp" /> : cover.webp ? <source srcSet={cover.webp} type="image/webp" /> : null}
            <img src={cover.src} alt="" width={cover.width} height={cover.height} loading={eager ? "eager" : "lazy"} />
        </picture>
    ) : (
        <BrandedCover column={articleColumn(article)} label={BLOG_UI[locale][articleColumn(article)]} />
    );
}

export function BlogCard({ article, locale, featured = false, related = false }: { article: CardArticle; locale: BlogLocale; featured?: boolean; related?: boolean }) {
    const { date } = useI18n();
    const column = articleColumn(article);
    const author = resolveBlogAuthor(article.author, locale);
    const Heading = related ? "h3" : "h2";
    const badge = <span className="isa-blog-category-pill">{BLOG_UI[locale][column]}</span>;
    const metadata = (
        <div className="isa-blog-card-meta">
            <span>{readingLabel(locale, articleReadingMinutes(article))}</span>
            <span aria-hidden="true">·</span>
            <time dateTime={article.date}>{date(article.date, { year: "numeric", month: "short", day: "numeric" })}</time>
        </div>
    );
    return (
        <Link to={blogPath(locale, article.slug)} className={`yingce-blog-card${featured ? " isa-blog-card-lead" : ""}`} data-blog-card data-column={column} data-scroll-reveal={featured ? undefined : `card:${article.slug}`} data-scroll-scene={featured || undefined} aria-label={article.title}>
            <div className="yingce-blog-card-cover">
                <BlogCover article={article} locale={locale} eager={featured} />
                {!featured ? badge : null}
            </div>
            <div className="yingce-blog-card-body" data-scroll-fade={featured || undefined}>
                {featured ? (
                    <div className="isa-blog-lead-meta">
                        {badge}
                        {metadata}
                    </div>
                ) : null}
                <Heading>{article.title}</Heading>
                {featured ? (
                    <>
                        <p className="isa-blog-lead-summary">{article.summary}</p>
                        <span className="isa-blog-author isa-blog-lead-author"><AuthorAvatar author={author} />{author.name}</span>
                        <span className="isa-blog-read">
                            {BLOG_READING_UI[locale].readNow}
                            <ArrowRight aria-hidden="true" />
                        </span>
                    </>
                ) : (
                    metadata
                )}
            </div>
        </Link>
    );
}

export function BlogGrid({ articles, locale, related = false }: { articles: CardArticle[]; locale: BlogLocale; related?: boolean }) {
    return (
        <div className="yingce-blog-grid">
            {articles.map((article) => (
                <BlogCard key={article.slug} article={article} locale={locale} related={related} />
            ))}
        </div>
    );
}
