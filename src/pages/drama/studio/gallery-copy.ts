export function watchText(key: Key, values: Record<string, number | string> = {}) {
    const copy = galleryTranslations[resolveAppLocale()] || galleryTranslations["en-US"];
    return copy[keys.indexOf(key)].replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}
